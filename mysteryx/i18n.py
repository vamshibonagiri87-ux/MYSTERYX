def current_language() -> str:
    return st.session_state.get("mysteryx_language", "en")


def language_name(code: str) -> str:
    return LANGUAGES.get(code, LANGUAGES["en"])


def tr(text: str, language_code: str | None = None, **values) -> str:
    translated = _TEXT.get(language_code or current_language(), {}).get(text, text)
    return translated.format(**values) if values else translated
